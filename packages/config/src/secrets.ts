import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { parseEnv } from 'node:util';
import type { z } from 'zod';
import { type EnvSource, parse } from './parse.ts';
import { clientSchema, serverSchema } from './schema.ts';

export const SECRET_NAME = 'SUTRA_ENV';

const fullSchema = serverSchema.extend(clientSchema.shape);

/** Validates server and client keys together, throwing one error listing every problem. */
export const check = (source: EnvSource) => parse(fullSchema, source);

/** `.env.example` contents, derived from the schemas (descriptions, examples, defaults). */
export function envExample(): string {
  const entries = Object.entries(fullSchema.shape as Record<string, z.ZodType>).map(
    ([key, field]) => {
      const meta = field.meta() ?? {};
      const fallback = field.safeParse(undefined);
      const note = !fallback.success
        ? ''
        : fallback.data === undefined
          ? ' (optional)'
          : ` (default: ${String(fallback.data)})`;
      return `# ${meta.description ?? key}${note}\n${key}=${String(meta.example ?? '')}`;
    },
  );
  return [
    '# Generated by `pnpm secrets:example` from packages/config/src/schema.ts. Do not edit.',
    '# Copy to .env.local (or run `pnpm secrets:pull`) and fill in real values.',
    '',
    entries.join('\n\n'),
    '',
  ].join('\n');
}

export type Gcloud = (args: string[]) => string;

export const gcloud: Gcloud = (args) =>
  execFileSync('gcloud', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });

const projectArgs = (project?: string) => (project ? [`--project=${project}`] : []);

/** Latest `SUTRA_ENV` value as dotenv text. */
export const pull = (run: Gcloud, project?: string) =>
  run([
    'secrets',
    'versions',
    'access',
    'latest',
    `--secret=${SECRET_NAME}`,
    ...projectArgs(project),
  ]);

function exists(run: Gcloud, p: string[]): boolean {
  try {
    run(['secrets', 'describe', SECRET_NAME, '--format=value(name)', ...p]);
    return true;
  } catch {
    return false;
  }
}

/**
 * Uploads `file` as a new `SUTRA_ENV` version (creating the secret if needed), then destroys
 * every older version so exactly one stays active. Refuses to upload an invalid env.
 * Returns the new version id.
 */
export function push(run: Gcloud, file: string, project?: string): string {
  check(parseEnv(readFileSync(file, 'utf8')));
  const p = projectArgs(project);
  const data = `--data-file=${file}`;
  if (exists(run, p)) run(['secrets', 'versions', 'add', SECRET_NAME, data, ...p]);
  else run(['secrets', 'create', SECRET_NAME, '--replication-policy=automatic', data, ...p]);
  const versions = run([
    'secrets',
    'versions',
    'list',
    SECRET_NAME,
    '--filter=NOT state:destroyed',
    '--format=value(name.basename())',
    ...p,
  ])
    .split('\n')
    .map((v) => v.trim())
    .filter(Boolean)
    .sort((a, b) => Number(b) - Number(a));
  const [latest, ...older] = versions;
  if (!latest) throw new Error(`${SECRET_NAME} has no active version after push`);
  for (const version of older) {
    run(['secrets', 'versions', 'destroy', version, `--secret=${SECRET_NAME}`, '--quiet', ...p]);
  }
  return latest;
}

export const writeSecretFile = (path: string, contents: string) =>
  writeFileSync(path, contents, { mode: 0o600 });
