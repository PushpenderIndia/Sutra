import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { evaluateBandit } from './datasets/bandit.ts';
import { evaluateCopilot } from './datasets/copilot.ts';
import { evaluateProfiler } from './datasets/profiler.ts';
import { evaluateReply } from './datasets/reply.ts';
import { evaluateScorer } from './datasets/scorer.ts';
import { evaluateVariant } from './datasets/variant.ts';
import { type EvalReport, type Metric, reportPassed } from './framework.ts';

/**
 * The one eval runner (PR 18): `pnpm eval [agent]` loads every set, scores it offline against the
 * fixtures and the deterministic rubric judge, and writes `evals/report.md` (used in the pitch). Pass
 * an agent name to run one set. The live LLM-judged variants run with `--live` (not in CI).
 */
export const EVALUATORS: Record<string, () => EvalReport> = {
  profiler: evaluateProfiler,
  scorer: evaluateScorer,
  variantWriter: evaluateVariant,
  replyAnalyst: evaluateReply,
  copilot: evaluateCopilot,
  bandit: evaluateBandit,
};

/** Runs every eval set (or just `agent`), in the table order of the plan. */
export function runEvals(agent?: string): EvalReport[] {
  const names = agent ? [agent] : Object.keys(EVALUATORS);
  return names.map((name) => {
    const evaluate = EVALUATORS[name];
    if (!evaluate)
      throw new Error(`Unknown eval agent "${name}". Known: ${Object.keys(EVALUATORS).join(', ')}`);
    return evaluate();
  });
}

const pct = (n: number) => `${(n * 100).toFixed(1)}%`;
const fmt = (m: Metric) =>
  m.unit === '%'
    ? `${pct(m.value)} (target ${pct(m.target)})`
    : `${m.value.toFixed(3)} (target ${m.target})`;

/** Renders the reports as the committed `evals/report.md`. */
export function renderReport(reports: EvalReport[]): string {
  const allPass = reports.every(reportPassed);
  const lines: string[] = [
    '# Sutra — eval report',
    '',
    '> Generated by `pnpm eval`. Every set runs offline against fixtures and the deterministic rubric',
    '> judge; the LLM-judged and live-model variants run with `pnpm eval <agent> --live`.',
    '',
    `**Status: ${allPass ? '✅ all targets met' : '❌ a target was missed'}**`,
    '',
    '| Agent | Cases | Metric | Result | |',
    '|---|---|---|---|---|',
  ];
  for (const r of reports)
    for (const m of r.metrics)
      lines.push(`| ${r.agent} | ${r.cases} | ${m.name} | ${fmt(m)} | ${m.pass ? '✅' : '❌'} |`);
  lines.push('');
  for (const r of reports) {
    lines.push(`### ${r.agent}`, '', r.description, '');
    for (const m of r.metrics)
      lines.push(
        `- ${m.pass ? '✅' : '❌'} **${m.name}** — ${fmt(m)}${m.note ? ` · ${m.note}` : ''}`,
      );
    lines.push('');
  }
  return `${lines.join('\n')}\n`;
}

const REPORT_PATH = fileURLToPath(new URL('./report.md', import.meta.url));

/** Writes `evals/report.md` and returns whether every target was met. */
export function writeReport(reports: EvalReport[]): boolean {
  writeFileSync(REPORT_PATH, renderReport(reports));
  return reports.every(reportPassed);
}

// CLI entry: `node evals/run.ts [agent]`.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const agent = process.argv.find((a) => a in EVALUATORS);
  const reports = runEvals(agent);
  const pass = writeReport(reports);
  process.stdout.write(renderReport(reports));
  process.stdout.write(`\nWrote ${REPORT_PATH}\n`);
  if (!pass) process.exit(1);
}
