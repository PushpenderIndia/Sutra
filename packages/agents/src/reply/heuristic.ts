/** Default sentiment for an intent (overridable per case). */
const SENTIMENT: Record<ReplyIntent, ReplyAnalysis['sentiment']> = {
  interested: 'positive',
  meeting_request: 'positive',
  question: 'neutral',
  objection: 'negative',
  not_now: 'neutral',
  not_interested: 'negative',
  unsubscribe: 'negative',
  out_of_office: 'neutral',
  wrong_person: 'neutral',
  referral: 'positive',
  other: 'neutral',
};

const classifyIntent = (text: string): ReplyIntent => {
  const haystack = text.toLowerCase();
  for (const { intent, words } of SIGNALS)
    if (words.some((w) => haystack.includes(w.toLowerCase()))) return intent;
  // A bare question mark with no stronger signal is a question.
  if (haystack.includes('?') || haystack.includes('？')) return 'question';
  return 'other';
};

/** Classifies one reply deterministically. `summaryEn` echoes the first line, truncated. */
export function heuristicAnalyze(reply: string, locale: Locale = 'en'): ReplyAnalysis {
  const intent = classifyIntent(reply);
  const firstLine = reply.trim().split(/\r?\n/)[0] ?? '';
  return {
    intent,
    sentiment: SENTIMENT[intent],
    language: locale,
    summaryEn: firstLine.slice(0, 200) || `(${intent})`,
  };
}
